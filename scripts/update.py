#!/usr/bin/env python3
"""Sync the Spotify cask when it matches SpotX's supported version."""

import hashlib
import json
import re
import urllib.request
from pathlib import Path

SPOTIFY = "https://raw.githubusercontent.com/Homebrew/homebrew-cask/HEAD/Casks/s/spotify.rb"
API = "https://api.github.com/repos/SpotX-Official/SpotX-Bash/commits/main"
RAW = "https://raw.githubusercontent.com/SpotX-Official/SpotX-Bash/{}/spotx.sh"
CASK = Path(__file__).resolve().parents[1] / "Casks/spotify.rb"


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "personal-homebrew-tap"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


commit = json.loads(fetch(API))["sha"]
if not re.fullmatch(r"[0-9a-f]{40}", commit):
    raise ValueError("Invalid upstream commit")
script = fetch(RAW.format(commit))
match = re.search(rb'^buildVer="([0-9]+(?:\.[0-9]+){3})\.g[0-9a-f]+"$', script, re.MULTILINE)
if not match:
    raise ValueError("Could not find SpotX's supported Spotify version")
supported = match.group(1).decode()
upstream = fetch(SPOTIFY).decode()
version = re.search(r'^  version "([0-9]+(?:\.[0-9]+){3})"$', upstream, re.MULTILINE)
if not version:
    raise ValueError("Could not find the official Spotify cask version")
if version.group(1) != supported:
    print(f"Waiting: Spotify {version.group(1)}, SpotX supports {supported}")
    raise SystemExit(0)
if not upstream.endswith("end\n") or '  app "Spotify.app"' not in upstream:
    raise ValueError("Unexpected official cask structure; review before syncing")
livecheck = '  livecheck do\n    url :url\n    strategy :extract_plist\n  end\n\n'
if livecheck not in upstream or '  auto_updates true\n' not in upstream:
    raise ValueError("Unexpected official cask update settings; review before syncing")

checksum = hashlib.sha256(script).hexdigest()
addition = '''
  # Validate the rolling Spotify download before installing or patching it.
  preflight do
    system_command "/bin/bash", args: ["-c", <<~EOS, "--", "#{staged_path}/Spotify.app", "#{version.csv.first}"], must_succeed: true
      set -e
      actual=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$1/Contents/Info.plist")
      actual=${actual%%.g*}
      if [ "$actual" != "$2" ]; then
        echo "SpotX supports Spotify $2, but the downloaded app is $actual. Try again when the tap is updated." >&2
        exit 1
      fi
    EOS
  end

  postflight do
    system_command "/bin/bash", args: ["-c", <<~EOS, "--", "#{appdir}", "#{version.csv.second}"], must_succeed: true
      set -e
      script=$(/usr/bin/mktemp "${TMPDIR:-/tmp}/spotx.XXXXXXXX")
      trap 'rm -f "$script"' EXIT
      /usr/bin/curl -fsSL "https://raw.githubusercontent.com/SpotX-Official/SpotX-Bash/$2/spotx.sh" -o "$script"
      echo "CHECKSUM  $script" | /usr/bin/shasum -a 256 -c -
      /bin/bash "$script" -B -d --noninteractive -P "$1"
    EOS
  end
'''.replace("CHECKSUM", checksum)

# A commit component causes SpotX-only updates to be visible to Homebrew.
upstream = upstream[:version.start(1)] + f"{supported},{commit}" + upstream[version.end(1):]
upstream = upstream.replace(livecheck, "", 1).replace('  auto_updates true\n', "", 1)
CASK.write_text("# Generated by scripts/update.py; do not edit by hand.\n" + upstream[:-4] + addition + "end\n")
